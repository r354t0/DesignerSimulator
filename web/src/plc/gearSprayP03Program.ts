import {
  createRung, createTag, insertInstruction, setRungComment,
  createIndependentParallelBranch, insertIntoIndependentOrUpper,
  addParallelContact, setTagValue,
  type PracticeProject, type PracticeInstruction,
} from "./practiceDocument.ts";
import {createGearPhase3AProject} from "./gearSprayPhase3Program.ts";

/** Port of P03_Cycle_Manager, with requested conversion rung removed.
 * FB_GearSpray_Sequence runs in rung 5 via the executable GEAR_SEQ block,
 * never as an unobservable SCADA-side automation.
 * Note: P04/P05/P06/P07 remain unported.
 */
export const GEAR_P03_TAGS=[
  ["TMR_Freq","TIMER","P03 R2: TON entre lubricaciones"],
  ["TMR_Startup_Cycle","TIMER","P03 R3: TON de arranque (1000 ms)"],
  ["CTN_Lubeflo","COUNTER","P03 R4: pulsos de lubricante"],
  ["DO_LS_Healthy","BOOL","Permiso de sistema saludable (P05 pendiente)"],
  ["ST_General_Trip_Rly","BOOL","Falla general (P05 pendiente)"],
  ["SM_Cycle_State","DINT","P03 R5: 0/10/20/30/90"],
  ["SM_Cycle_Blocked","BOOL","P03 R5: estado bloqueado"],
  ["SM_Cycle_RearmHold","BOOL","P03 R5: espera de rearme"],
  ["SM_Cycle_BlockLatched","BOOL","P03 R5: memoria interna de bloqueo"],
  ["ST_Cycle_Rly","BOOL","P03 R5: ciclo de lubricación activo"],
  ["DO_Lubecon_Sol","BOOL","P03 R6: mando de válvula de lubricante"],
  ["ST_Pump_Rly","BOOL","P03 R7: solicitud de bomba (P04 pendiente)"],
  ["TMR_Purge","TIMER","P03 R8: TOF de purga"],
  ["ST_Airsol_Rly","BOOL","P03 R9: habilitación aire atomizador"],
] as const;

type Spec=Partial<Pick<PracticeInstruction,
  "kind"|"tag"|"preset"|"compareA">> &
  Pick<PracticeInstruction,"kind"|"tag">;
const x=(tag:string):Spec=>({kind:"XIC",tag});
const nx=(tag:string):Spec=>({kind:"XIO",tag});
const o=(tag:string):Spec=>({kind:"OTE",tag});

export function createGearPhase3Project():PracticeProject {
  let p=createGearPhase3AProject();
  for(const [name,type,description] of GEAR_P03_TAGS)
    p=createTag(p,name,description,type);
  // P05 is not ported yet. TEMPORARY permissive for SCADA FAT of P03,
  // explicitly editable as a tag; never claim healthy alarm logic exists.
  p=setTagValue(p,"DO_LS_Healthy",true);
  // P01 physical lubricant terminal is generated by P03 DO_Lubecon_Sol.
  // Keep its original P01 output rung in its original position.
  p={...p,rungs:p.rungs.map(r=>r.id!=="gear3a-p01-output-2"?r:{
    ...r,instructions:r.instructions.map(i=>
      i.kind==="XIC"&&i.tag==="Lubecon_Sol"?
      {...i,tag:"DO_Lubecon_Sol"}:i),
  })};
  let seq=0;
  function add(id:string,ins:Spec[],comment?:string){
    p=createRung(p,id);
    ins.forEach((item,k)=>{p=insertInstruction(p,id,k,{
      id:"gear-p03-"+(++seq),...item,
    });});
    if(comment)p=setRungComment(p,id,comment);
  }
  type Group={or:Spec[][]}|Spec;
  function logic(id:string,parts:Group[],coil:Spec,comment?:string){
    add(id,[coil],comment);
    for(const item of parts){
      if(!("or" in item)){
        const r=p.rungs.find(r=>r.id===id)!;
        const at=r.instructions.filter(i=>i.kind!=="OTE").length;
        p=insertInstruction(p,id,at,{id:"gear-p03-"+(++seq),...item});
      }else {
        if(item.or.length!==2||item.or.some(p=>p.length===0))
          throw Error("P03: OR inválido en "+id);
        p=createIndependentParallelBranch(p,id);
        const anchor=p.rungs.find(r=>r.id===id)!.instructions
          .findLast(i=>i.kind==="OR_JUNCTION")?.id;
        if(!anchor)throw Error("P03 sin OR junction "+id);
        for(const spec of item.or[0])
          p=insertIntoIndependentOrUpper(p,id,anchor,{
            id:"gear-p03-"+(++seq),...spec,
          });
        for(const spec of item.or[1])
          p=addParallelContact(p,id,anchor,{
            id:"gear-p03-"+(++seq),...spec,
          });
      }
    }
  }

  // Original P03 rung 2 becomes the first P03 rung (MOV conversion deleted).
  add("gear-p03-r02",[
    x("ST_Run_Rly"),nx("ST_Cycle_Rly"),nx("ST_Maint_Mode"),
    nx("SM_Cycle_Blocked"),nx("SM_Cycle_RearmHold"),
    {kind:"TON",tag:"TMR_Freq",preset:{mode:"tag",tag:"TMR_Freq_SP"}},
  ],"P03 — CYCLE MANAGER | Inicio: frecuencia (TMR_Freq_SP).");
  add("gear-p03-r03",[
    x("ST_Run_Rly"),nx("PB_Reset"),
    {kind:"TON",tag:"TMR_Startup_Cycle",preset:{mode:"literal",value:1000}},
  ]);
  add("gear-p03-r04",[
    x("ST_Run_Rly"),x("DI_PDB"),
    {kind:"CTU",tag:"CTN_Lubeflo",preset:{mode:"tag",tag:"CNT_LubeFlo_SP"}},
  ]);
  add("gear-p03-r05",[
    x("ST_Run_Rly"),{kind:"GEAR_SEQ",tag:"ST_Cycle_Rly"},
  ],"P03 — Rung 5 | FB_GearSpray_Sequence: estados 0/10/20/30/90.");
  // R6: (Run && Cycle) OR pressure release. Original CCW release bypasses Run.
  logic("gear-p03-r06",[
    {or:[[x("ST_Run_Rly"),x("ST_Cycle_Rly")],
      [x("PB_Lubpress_Release")]]},
  ],o("DO_Lubecon_Sol"));
  // R7: Run AND (Cycle OR AUTO) – same rung, no helper signal.
  logic("gear-p03-r07",[
    x("ST_Run_Rly"),
    {or:[[x("ST_Cycle_Rly")],[x("ST_Auto_Mode")]]},
  ],o("ST_Pump_Rly"));
  add("gear-p03-r08",[
    x("ST_Run_Rly"),x("ST_Cycle_Rly"),
    {kind:"TOF",tag:"TMR_Purge",preset:{mode:"literal",value:30000}},
  ]);
  add("gear-p03-r09",[
    x("ST_Run_Rly"),x("TMR_Purge.DN"),o("ST_Airsol_Rly"),
  ]);
  add("gear-p03-r10",[
    x("ST_Run_Rly"),x("ST_Airsol_Rly"),o("Air_Sol"),
  ]);
  // R11: reset the CTU with a native RES output on this SAME original rung.
  // The counter was already evaluated in R4, so reset executes at R11.
  logic("gear-p03-r11",[
    {or:[[nx("TMR_Purge.DN")],[nx("ST_Run_Rly")]]},
  ],{kind:"RES",tag:"CTN_Lubeflo"});
  return p;
}
